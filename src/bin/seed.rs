/// Утилита для загрузки расписания 9А прямо в БД бота.
/// Запуск: cargo run --bin seed
/// Предварительно нужно отправить /start боту, чтобы в БД появился chat_id.
use rusqlite::{Connection, params};

fn main() {
    dotenv::dotenv().ok();

    let conn = Connection::open("bot_data.db")
        .expect("Не удалось открыть bot_data.db — запусти бота и отправь /start сначала");

    // Берём первый (единственный) chat_id из таблицы users
    let chat_id: i64 = conn
        .query_row("SELECT chat_id FROM users LIMIT 1", [], |r| r.get(0))
        .expect("Нет пользователей в БД — отправь /start боту и поделись геолокацией");

    println!("📋 Загружаю расписание для chat_id = {chat_id}");

    // Чистим старое расписание
    conn.execute("DELETE FROM schedule WHERE chat_id = ?1", params![chat_id])
        .expect("Ошибка очистки расписания");

    // Расписание 9А клас
    // day_of_week: 0=Пн, 1=Вт, 2=Ср, 3=Чт, 4=Пт
    let schedule: &[(u8, &str, &str)] = &[
        // ── Понеділок ──────────────────────────────
        (0, "09:00", "Алгебра"),
        (0, "09:55", "Алгебра"),
        (0, "10:50", "ІТ / Англ. мова"),
        (0, "12:20", "ІТ / Англ. мова"),
        (0, "13:15", "Укр. література"),
        (0, "14:10", "Географія"),
        (0, "15:05", "Виховна година"),

        // ── Вівторок ───────────────────────────────
        (1, "09:00", "Геометрія"),
        (1, "09:55", "Геометрія"),
        (1, "10:50", "Укр. мова"),
        (1, "12:20", "Укр. мова"),
        (1, "13:15", "Історія: Україна і світ"),
        (1, "14:10", "Історія: Україна і світ"),

        // ── Середа ─────────────────────────────────
        (2, "09:00", "Англ. мова / ІТ"),
        (2, "09:55", "Англ. мова / ІТ"),
        (2, "10:50", "ІТ / Англ. мова"),
        (2, "12:20", "ІТ / Англ. мова"),
        (2, "13:15", "Алгебра"),
        (2, "14:10", "Хімія"),
        (2, "15:05", "Зар. література"),

        // ── Четвер ─────────────────────────────────
        (3, "09:00", "Біологія"),
        (3, "09:55", "Фізика"),
        (3, "10:50", "Укр. мова"),
        (3, "12:20", "Геометрія"),
        (3, "13:15", "Правознавство"),
        (3, "14:10", "Англ. мова"),

        // ── П'ятниця ───────────────────────────────
        (4, "09:00", "Біологія"),
        (4, "09:55", "Хімія"),
        (4, "10:50", "Англ. мова / ІТ"),
        (4, "12:20", "Англ. мова / ІТ"),
        (4, "13:15", "Фізика"),
        (4, "14:10", "Фізика"),
    ];

    let mut count = 0;
    for (day, time, subject) in schedule {
        conn.execute(
            "INSERT INTO schedule (chat_id, day_of_week, time_str, subject) VALUES (?1, ?2, ?3, ?4)",
            params![chat_id, day, time, subject],
        ).expect("Ошибка вставки");
        count += 1;
    }

    println!("✅ Загружено {count} уроков!");
    println!("📱 Напиши /расписание в боте чтобы проверить.");
}
